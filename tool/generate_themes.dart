// Generates lib/src/theme/themes/*.g.dart from the CDS React Native theme files
// (github.com/coinbase/cds, packages/mobile/src/themes).
//
// Usage: dart run tool/generate_themes.dart <path-to-cds>/packages/mobile/src/themes
import 'dart:io';

const _themes = {
  'defaultTheme.ts': 'Default',
  'defaultHighContrastTheme.ts': 'DefaultHighContrast',
};

const _hues = [
  'blue', 'green', 'orange', 'yellow', 'gray', 'indigo', //
  'pink', 'purple', 'red', 'teal', 'chartreuse',
];
const _steps = [0, 5, 10, 15, 20, 30, 40, 50, 60, 70, 80, 90, 100];

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/generate_themes.dart <cds>/packages/mobile/src/themes');
    exit(64);
  }
  for (final entry in _themes.entries) {
    final source = File('${args.single}/${entry.key}').readAsStringSync();
    final dart = _generate(source, entry.value);
    final fileName = _snake(entry.value);
    File('lib/src/theme/themes/${fileName}_theme_colors.g.dart').writeAsStringSync(dart);
    stdout.writeln('Generated ${fileName}_theme_colors.g.dart');
  }
}

String _snake(String s) =>
    s.replaceAllMapped(RegExp('[A-Z]'), (m) => '_${m[0]!.toLowerCase()}').substring(1);

Map<String, List<int>> _spectrum(String source, String name) {
  final block = RegExp('const $name = \\{([^}]*)\\}').firstMatch(source)![1]!;
  final out = <String, List<int>>{};
  for (final m in RegExp(r"(\w+): '(\d+),(\d+),(\d+)'").allMatches(block)) {
    out[m[1]!] = [int.parse(m[2]!), int.parse(m[3]!), int.parse(m[4]!)];
  }
  return out;
}

String _hex(List<int> rgb, [double alpha = 1]) {
  final a = (alpha * 255).round();
  String h(int v) => v.toRadixString(16).padLeft(2, '0').toUpperCase();
  return 'Color(0x${h(a)}${h(rgb[0])}${h(rgb[1])}${h(rgb[2])})';
}

String _generate(String source, String prefix) {
  final light = _spectrum(source, 'lightSpectrum');
  final dark = _spectrum(source, 'darkSpectrum');
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/generate_themes.dart from the CDS React Native theme.')
    ..writeln('// Do not edit by hand. Color values: Copyright Coinbase, Apache-2.0.')
    ..writeln()
    ..writeln("import 'dart:ui' show Color;")
    ..writeln()
    ..writeln("import '../cds_color_palette.dart';")
    ..writeln("import '../cds_spectrum.dart';")
    ..writeln();

  void spectrum(String name, Map<String, List<int>> s) {
    b.writeln('const CdsSpectrum cds$prefix${name}Spectrum = CdsSpectrum({');
    for (final hue in _hues) {
      final colors = _steps.map((step) => _hex(s['$hue$step']!)).join(', ');
      b.writeln('  CdsHue.$hue: [$colors],');
    }
    b.writeln('});');
    b.writeln();
  }

  spectrum('Light', light);
  spectrum('Dark', dark);

  void palette(String name, String blockName, Map<String, List<int>> s) {
    final start = source.indexOf('$blockName: {');
    final end = source.indexOf('\n  },', start);
    final block = source.substring(start, end);
    b.writeln('const CdsColorPalette cds$prefix${name}Palette = CdsColorPalette(');
    final line = RegExp(r'(\w+): `rgba?\(\$\{\w+\.(\w+)\}(?:,([\d.]+))?\)`');
    for (final m in line.allMatches(block)) {
      final rgb = s[m[2]!]!;
      final alpha = m[3] == null ? 1.0 : double.parse(m[3]!);
      b.writeln('  ${m[1]}: ${_hex(rgb, alpha)}, // ${m[2]}${m[3] == null ? '' : ' @ ${m[3]}'}');
    }
    b.writeln(');');
    b.writeln();
  }

  palette('Light', 'lightColor', light);
  palette('Dark', 'darkColor', dark);
  return b.toString();
}
