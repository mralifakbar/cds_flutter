// Generates lib/src/icons/cds_icon_name.g.dart and cds_icon_keywords.g.dart
// from a checkout of github.com/coinbase/cds (packages/icons/src), skipping
// the brand marks listed in tool/excluded_icons.txt.
//
// Usage: dart run tool/generate_icons.dart <path-to-cds>/packages/icons/src
import 'dart:io';

const _dartReserved = {'factory'};

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/generate_icons.dart <cds>/packages/icons/src');
    exit(64);
  }
  final src = args.single;
  final glyphSource = File('$src/glyphMap.ts').readAsStringSync();
  final descriptionSource = File('$src/descriptionMap.ts').readAsStringSync();

  final glyphs = <String, int>{};
  final glyphLine = RegExp(r"'([A-Za-z0-9]+)-(12|16|24)-(active|inactive)':\s*'(.+?)'");
  for (final m in glyphLine.allMatches(glyphSource)) {
    glyphs['${m[1]}-${m[2]}-${m[3]}'] = m[4]!.runes.single;
  }
  final excluded = File('tool/excluded_icons.txt')
      .readAsLinesSync()
      .map((l) => l.trim())
      .where((l) => l.isNotEmpty && !l.startsWith('#'))
      .toSet();
  glyphs.removeWhere((key, _) => excluded.contains(key.split('-').first));
  final names = glyphs.keys.map((k) => k.split('-').first).toSet().toList()..sort();

  final keywords = <String, Set<String>>{};
  final entry = RegExp(r"'([^']+)':\s*\[([^\]]*)\]", multiLine: true);
  for (final m in entry.allMatches(descriptionSource)) {
    final description = m[1]!;
    for (final n in RegExp(r"'([^']+)'").allMatches(m[2]!)) {
      keywords.putIfAbsent(n[1]!, () => {}).add(description);
    }
  }

  String ident(String name) => _dartReserved.contains(name) ? '${name}Icon' : name;
  String hex(int? v) => v == null ? '0' : '0x${v.toRadixString(16).toUpperCase()}';

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_icons.dart. Do not edit by hand.')
    ..writeln('// Glyphs come from the CDS icon font (Apache-2.0, Coinbase).')
    ..writeln()
    ..writeln("part of 'cds_icon_name.dart';")
    ..writeln()
    ..writeln('/// Every glyph in the CDS icon font. ${names.length} icons.')
    ..writeln('enum CdsIconName {');
  for (final name in names) {
    final cps = [
      for (final size in [12, 16, 24])
        for (final state in ['active', 'inactive']) hex(glyphs['$name-$size-$state']),
    ];
    out.writeln("  ${ident(name)}('$name', [${cps.join(', ')}]),");
  }
  out
    ..writeln('  ;')
    ..writeln()
    ..writeln('  const CdsIconName(this.cdsName, this._glyphs);')
    ..writeln()
    ..writeln('  /// The name used by CDS web and React Native (`<Icon name="..." />`).')
    ..writeln('  final String cdsName;')
    ..writeln()
    ..writeln('  /// Codepoints ordered 12 active, 12 inactive, 16 active, 16 inactive, 24 active, 24 inactive.')
    ..writeln('  final List<int> _glyphs;')
    ..writeln('}');
  File('lib/src/icons/cds_icon_name.g.dart').writeAsStringSync(out.toString());

  final kw = StringBuffer()
    ..writeln('// GENERATED by tool/generate_icons.dart. Do not edit by hand.')
    ..writeln()
    ..writeln("import 'cds_icon_name.dart';")
    ..writeln()
    ..writeln('/// Search keywords for each icon, taken from the CDS icon description map.')
    ..writeln('/// Kept in its own library so apps that never search icons do not ship it.')
    ..writeln('const Map<CdsIconName, List<String>> cdsIconKeywords = {');
  for (final name in names) {
    final words = (keywords[name] ?? {}).toList()..sort();
    if (words.isEmpty) continue;
    final quoted = words.map((w) => "'${w.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'");
    kw.writeln('  CdsIconName.${ident(name)}: [${quoted.join(', ')}],');
  }
  kw.writeln('};');
  File('lib/src/icons/cds_icon_keywords.g.dart').writeAsStringSync(kw.toString());

  stdout.writeln('Generated ${names.length} icons, ${glyphs.length} glyphs.');
}
